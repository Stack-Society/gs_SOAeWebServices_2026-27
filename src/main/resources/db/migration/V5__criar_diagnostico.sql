-- V5: diagnóstico de cada questionário respondido, com as respostas e o resultado do modelo de IA
-- Só questionários válidos são gravados: os inválidos são recusados antes (falha fechada).

CREATE TABLE GS2627_1_diagnostico (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id       NUMBER        NOT NULL,
    serie          NUMBER(1)     NOT NULL,
    data_hora      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    versao_modelo  VARCHAR2(10)  NOT NULL,
    CONSTRAINT ck_diagnostico_serie CHECK (serie BETWEEN 1 AND 5),
    CONSTRAINT fk_diagnostico_aluno FOREIGN KEY (aluno_id) REFERENCES GS2627_1_aluno (id)
);

-- As 24 respostas marcadas pelo aluno
CREATE TABLE GS2627_1_resposta (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnostico_id  NUMBER     NOT NULL,
    numero          NUMBER(2)  NOT NULL,
    alternativa     CHAR(1)    NOT NULL,
    CONSTRAINT uk_resposta_diag_numero UNIQUE (diagnostico_id, numero),
    CONSTRAINT ck_resposta_numero CHECK (numero BETWEEN 1 AND 24),
    CONSTRAINT ck_resposta_alternativa CHECK (alternativa IN ('A', 'B', 'C')),
    CONSTRAINT fk_resposta_diagnostico FOREIGN KEY (diagnostico_id)
        REFERENCES GS2627_1_diagnostico (id) ON DELETE CASCADE
);

-- Resultado de cada um dos 8 conteúdos: acertos, probabilidade de lacuna e decisão
CREATE TABLE GS2627_1_resultado_conteudo (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnostico_id  NUMBER        NOT NULL,
    conteudo_id     NUMBER        NOT NULL,
    acertos         NUMBER(1)     NOT NULL,
    probabilidade   NUMBER(7,6)   NOT NULL,
    situacao        VARCHAR2(20)  NOT NULL,
    CONSTRAINT uk_resultado_diag_conteudo UNIQUE (diagnostico_id, conteudo_id),
    CONSTRAINT ck_resultado_acertos CHECK (acertos BETWEEN 0 AND 3),
    CONSTRAINT ck_resultado_probabilidade CHECK (probabilidade BETWEEN 0 AND 1),
    CONSTRAINT ck_resultado_situacao CHECK (situacao IN ('LACUNA', 'SEM_LACUNA', 'A_CONFIRMAR')),
    CONSTRAINT fk_resultado_diagnostico FOREIGN KEY (diagnostico_id)
        REFERENCES GS2627_1_diagnostico (id) ON DELETE CASCADE,
    CONSTRAINT fk_resultado_conteudo FOREIGN KEY (conteudo_id) REFERENCES GS2627_1_conteudo (id)
);

-- Nível do aluno em cada disciplina
CREATE TABLE GS2627_1_nivel_disciplina (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnostico_id  NUMBER        NOT NULL,
    disciplina_id   NUMBER        NOT NULL,
    nivel           VARCHAR2(20)  NOT NULL,
    CONSTRAINT uk_nivel_diag_disciplina UNIQUE (diagnostico_id, disciplina_id),
    CONSTRAINT ck_nivel_valor CHECK (nivel IN ('ADEQUADO', 'EM_DESENVOLVIMENTO', 'ABAIXO_DO_ESPERADO', 'A_CONFIRMAR')),
    CONSTRAINT fk_nivel_diagnostico FOREIGN KEY (diagnostico_id)
        REFERENCES GS2627_1_diagnostico (id) ON DELETE CASCADE,
    CONSTRAINT fk_nivel_disciplina FOREIGN KEY (disciplina_id) REFERENCES GS2627_1_disciplina (id)
);
