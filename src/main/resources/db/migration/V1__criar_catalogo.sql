-- V1: catálogo do questionário (disciplinas, conteúdos e questões com gabarito por série)

CREATE TABLE GS2627_1_disciplina (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR2(30)  NOT NULL,
    nome        VARCHAR2(60)  NOT NULL,
    CONSTRAINT uk_disciplina_codigo UNIQUE (codigo)
);

CREATE TABLE GS2627_1_conteudo (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR2(30)   NOT NULL,
    nome           VARCHAR2(60)   NOT NULL,
    ordem_modelo   NUMBER(2)      NOT NULL,
    estrategia     VARCHAR2(500)  NOT NULL,
    disciplina_id  NUMBER         NOT NULL,
    CONSTRAINT uk_conteudo_codigo UNIQUE (codigo),
    CONSTRAINT uk_conteudo_ordem UNIQUE (ordem_modelo),
    CONSTRAINT ck_conteudo_ordem CHECK (ordem_modelo BETWEEN 0 AND 7),
    CONSTRAINT fk_conteudo_disciplina FOREIGN KEY (disciplina_id) REFERENCES GS2627_1_disciplina (id)
);

CREATE TABLE GS2627_1_questao (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serie        NUMBER(1)    NOT NULL,
    numero       NUMBER(2)    NOT NULL,
    gabarito     CHAR(1)      NOT NULL,
    conteudo_id  NUMBER       NOT NULL,
    CONSTRAINT uk_questao_serie_numero UNIQUE (serie, numero),
    CONSTRAINT ck_questao_serie CHECK (serie BETWEEN 1 AND 5),
    CONSTRAINT ck_questao_numero CHECK (numero BETWEEN 1 AND 24),
    CONSTRAINT ck_questao_gabarito CHECK (gabarito IN ('A', 'B', 'C')),
    CONSTRAINT fk_questao_conteudo FOREIGN KEY (conteudo_id) REFERENCES GS2627_1_conteudo (id)
);
