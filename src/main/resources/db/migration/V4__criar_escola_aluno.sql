-- V4: escolas e alunos (sem dados pessoais: o aluno é identificado só por um código anônimo)

CREATE TABLE GS2627_1_escola (
    id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR2(20)   NOT NULL,
    nome    VARCHAR2(100)  NOT NULL,
    CONSTRAINT uk_escola_codigo UNIQUE (codigo)
);

CREATE TABLE GS2627_1_aluno (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     VARCHAR2(20)  NOT NULL,
    serie      NUMBER(1)     NOT NULL,
    escola_id  NUMBER        NOT NULL,
    CONSTRAINT uk_aluno_codigo UNIQUE (codigo),
    CONSTRAINT ck_aluno_serie CHECK (serie BETWEEN 1 AND 5),
    CONSTRAINT fk_aluno_escola FOREIGN KEY (escola_id) REFERENCES GS2627_1_escola (id)
);
